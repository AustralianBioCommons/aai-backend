def is_australian_research_institution_email(email: str) -> bool:
    """Return True if the email domain is on the Australian Research Institutions list."""
    try:
        domain = email.lower().rsplit("@", 1)[-1]
    except Exception:
        return False
    return domain in AUSTRALIAN_RESEARCH_INSTITUTION_DOMAINS or domain.endswith(".gov.au")
